"""## 11. Global vs Training Correlation Comparison

Compares feature-type rankings **and classifier input pairs** from the training subset (2/3 trials, per fold)
vs correlations from the full dataset (global CSVs, all trials).

**Part A — Feature-type ranking agreement:**
- Spearman ρ between global feature ranking and per-fold training ranking
- Top-N Jaccard: fraction of top-N feature types that overlap

**Part B — Classifier input pair (feature × channel) overlap:**
- Training HIGH pairs = `{top-N feature types} × {all channels}` — the actual classifier input
- Global top-K pairs  = top-K (feature, channel) pairs from `spearman_channel_binary.csv` ranked by `abs_rho`
- **Precision**: fraction of training HIGH pairs that appear in global top-K
- **Recall**: fraction of global top-K pairs captured by training HIGH selection
- **Jaccard**: set overlap between the two pair sets
- Also compared for LOW pairs (expected: low overlap with global top pairs)
- Visualised as a heatmap: rows = feature types, cols = channels, cell colour = global `abs_rho`,
  with markers showing which cells are selected as HIGH / LOW by training

"""

