def run_n_sweep(data, folds, feature_cols, feat_types, channels,
                 n_values, channel_config):
    sweep_results = []
    models        = get_models()
    n_ch          = len(channels)

    for n in n_values:
        print(f'  N={n:>2} ({n}×{n_ch}={n*n_ch} cols) ...', end=' ')

        for fold_info in folds:
            train_idx = fold_info['train_idx']
            test_idx  = fold_info['test_idx']

            X_tr_full   = data.loc[train_idx, feature_cols]
            y_train     = data.loc[train_idx, 'stress_binary']   # for model training
            y_train_cont= data.loc[train_idx, 'stress_label']    # for Pearson ranking
            X_te_full   = data.loc[test_idx,  feature_cols]
            y_test      = data.loc[test_idx,  'stress_binary']

            scaler    = StandardScaler()
            X_tr_sc   = pd.DataFrame(scaler.fit_transform(X_tr_full),
                                      columns=feature_cols, index=train_idx)
            X_te_sc   = pd.DataFrame(scaler.transform(X_te_full),
                                      columns=feature_cols, index=test_idx)

            ranked, _ = rank_feature_types_by_pearson(
                X_tr_sc, y_train_cont, feat_types, channels)

            high_c, low_c, _, _ = select_feature_sets(ranked, channels, n, n)

            for feat_set_name, cols in [('HIGH', high_c), ('LOW', low_c)]:
                cols = [c for c in cols if c in X_tr_sc.columns]
                if not cols:
                    continue
                for model_name, model in models.items():
                    model.fit(X_tr_sc[cols], y_train)
                    y_pred = model.predict(X_te_sc[cols])
                    sweep_results.append({
                        'channel_config': channel_config,
                        'n_feat'        : n,
                        'n_columns'     : len(cols),
                        'feature_set'   : feat_set_name,
                        'model'         : model_name,
                        'fold'          : fold_info['fold'],
                        'accuracy'      : accuracy_score(y_test, y_pred),
                        'f1'            : f1_score(y_test, y_pred, zero_division=0)
                    })
        print('done')

    return pd.DataFrame(sweep_results)

