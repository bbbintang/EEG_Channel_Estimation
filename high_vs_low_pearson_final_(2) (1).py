def plot_confusion_matrices(conf_mats, config, results_df, output_dir):
    models       = list(results_df['model'].unique())
    feature_sets = ['HIGH', 'LOW', 'HIGH+LOW']
    n_rows, n_cols = len(feature_sets), len(models)

    fig, axes = plt.subplots(n_rows, n_cols,
                              figsize=(4.5 * n_cols, 4.0 * n_rows))
    fig.suptitle(f'Confusion Matrices — {config} Spearman (Summed 3 Folds)',
                 fontsize=14, fontweight='bold', y=1.01)

    for ri, feat_set in enumerate(feature_sets):
        for ci, model_name in enumerate(models):
            ax       = axes[ri][ci]
            cm_total = np.zeros((2, 2), dtype=int)
            for fold_num in [1, 2, 3]:
                key = (fold_num, feat_set, model_name)
                if key in conf_mats:
                    cm_total += conf_mats[key]

            ConfusionMatrixDisplay(cm_total,
                                   display_labels=['Non-Stress', 'Stress']
                                   ).plot(ax=ax, colorbar=False, cmap='Blues')

            mask     = ((results_df['feature_set'] == feat_set) &
                        (results_df['model']        == model_name))
