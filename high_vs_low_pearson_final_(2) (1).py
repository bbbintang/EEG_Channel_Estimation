"""## 4. Feature Type Ranking via Pearson Correlation (Per-Fold, No Leakage)

For each feature type (e.g. `delta_psd`), compute Pearson r between every `feat_type_{ch}` column  
and the binary stress label on **scaled training data only**, then average the |r| values across all  
channels to get a single score per feature type.

**Selection:**
- HIGH = top-N feature types × ALL channels → N × n_ch columns
- LOW  = bottom-N feature types × ALL channels → N × n_ch columns
- HIGH+LOW = union of both

No leakage: correlation computed on training data only (fit scaler on train).

"""

def rank_feature_types_by_pearson(X_train_sc, y_train, feat_types, channels):
    """
    Rank feature types by avg |Pearson r| across all channels.

    For each feature type ft:
      For each channel ch:
        Compute pearsonr(X_train_sc['{ft}_{ch}'], y_train) → r
      avg_abs_r(ft) = mean(|r| across channels)

    Returns:
        ranked : list of (feat_type, avg_abs_r, per_ch_r_dict) — sorted desc by avg_abs_r
        col_rho: dict { col_name : (r, abs_r, p) } for all individual columns
    """
    col_rho = {}
    for col in X_train_sc.columns:
        try:
            rho, p      = pearsonr(X_train_sc[col], y_train)
            col_rho[col] = (float(rho), abs(float(rho)), float(p))
        except Exception:
            col_rho[col] = (0.0, 0.0, 1.0)

    ranked = []
    for ft in feat_types:
        per_ch = {}
        abs_vals = []
        for ch in channels:
            col = f'{ft}_{ch}'
            if col in col_rho:
                per_ch[ch] = col_rho[col][0]
                abs_vals.append(col_rho[col][1])
        avg = float(np.mean(abs_vals)) if abs_vals else 0.0
        ranked.append((ft, avg, per_ch))

    ranked.sort(key=lambda x: x[1], reverse=True)
    return ranked, col_rho


def select_feature_sets(ranked, channels, n_top, n_bottom):
    """
    Build HIGH and LOW column sets.

    HIGH = top-n_top feature types × ALL channels
    LOW  = bottom-n_bottom feature types × ALL channels

    Returns:
        high_cols  : list[str]  (column names)
        low_cols   : list[str]
        high_feats : list[str]  (feature type names)
        low_feats  : list[str]
    """
    total = len(ranked)
    n_top    = min(n_top,    total // 2) or 1
    n_bottom = min(n_bottom, total // 2) or 1

    high_feats = [ft for ft, _, _ in ranked[:n_top]]
    low_feats  = [ft for ft, _, _ in ranked[-n_bottom:]]

    high_cols = [f'{ft}_{ch}' for ft in high_feats for ch in channels]
    low_cols  = [f'{ft}_{ch}' for ft in low_feats  for ch in channels]

    return high_cols, low_cols, high_feats, low_feats


