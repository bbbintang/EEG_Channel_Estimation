def load_global_channel_pairs(config):
    """
    Load global channel correlation CSV.
    Handles both Pearson (channel_correlations.csv) and Spearman (spearman_channel_binary.csv).

    Pearson CSV columns : feature_name, channel, correlation, abs_correlation, p_value, n_samples
    Spearman CSV columns: feature_name/feature, channel, spearman_rho, abs_rho, p_value, n_samples

    Returns:
        pairs_ranked : list of (feature, channel, abs_corr) sorted desc
        pair_rho_df  : DataFrame with columns [feature, channel, abs_rho] for heatmap use
    """
    df = pd.read_csv(GLOBAL_CHANNEL_CSVS[config])
    df.columns = [c.strip().lower().replace('-','_').replace(' ','_') for c in df.columns]

    ch_col   = next(c for c in df.columns if 'channel' in c)
    feat_col = next((c for c in df.columns if c in ('feature_name','feature')), None)
    if feat_col is None:
        feat_col = next(c for c in df.columns if 'feature' in c)

    # Prefer explicit abs_correlation (Pearson) then abs_rho (Spearman)
    if 'abs_correlation' in df.columns:
        abs_col = 'abs_correlation'
    elif 'abs_rho' in df.columns:
        abs_col = 'abs_rho'
    else:
        abs_col = next(c for c in df.columns if 'abs' in c)

    df = df.sort_values(abs_col, ascending=False).reset_index(drop=True)
    pairs_ranked = list(zip(df[feat_col], df[ch_col], df[abs_col]))

    pair_rho_df = df[[feat_col, ch_col, abs_col]].copy()
    pair_rho_df.columns = ['feature', 'channel', 'abs_rho']
    return pairs_ranked, pair_rho_df


def compare_pair_overlap(pairs_ranked_global, fold_rankings, channels,
                         top_k_global_list=(40, 80, 160)):
    """
    Compare training HIGH/LOW classifier input pairs vs global top-K pairs.

    Training HIGH pairs = {(ft, ch) : ft in high_feats, ch in all channels}
    Training LOW  pairs = {(ft, ch) : ft in low_feats,  ch in all channels}
    Global top-K  pairs = top-K (feature, channel) by global abs_rho

    Metrics per fold:
      - Precision : |train_set ∩ global_top_K| / |train_set|
                    (fraction of training pairs that are globally high)
      - Recall    : |train_set ∩ global_top_K| / |global_top_K|
                    (fraction of global top-K captured by training selection)
      - Jaccard   : |train_set ∩ global_top_K| / |train_set ∪ global_top_K|
    """
    global_pair_set_full = [(ft, ch) for ft, ch, _ in pairs_ranked_global]

    records = []

    for feat_set_label in ['HIGH', 'LOW']:
        print(f'\n  {feat_set_label} pairs vs Global top-K:')
        print(f'  {"Fold":<6}', end='')
        for k in top_k_global_list:
            print(f'  {"Top-"+str(k):>8} Prec  Rec   Jac', end='')
        print()
        print(f'  {"-"*6}', end='')
        for _ in top_k_global_list:
            print(f'  {"-"*8} {"─"*5} {"─"*5} {"─"*5}', end='')
        print()

        for fold in fold_rankings:
            fold_num   = fold['fold']
            feat_list  = fold['high_feats'] if feat_set_label == 'HIGH' else fold['low_feats']
            train_pairs = set((ft, ch) for ft in feat_list for ch in channels)

            print(f'  {fold_num:<6}', end='')
            fold_record = {'fold': fold_num, 'set': feat_set_label,
                           'n_train_pairs': len(train_pairs)}
            for k in top_k_global_list:
                global_top_k = set(global_pair_set_full[:k])
                intersect    = train_pairs & global_top_k
                union_       = train_pairs | global_top_k
                precision    = len(intersect) / len(train_pairs)   if train_pairs   else 0.0
                recall       = len(intersect) / len(global_top_k)  if global_top_k  else 0.0
                jaccard      = len(intersect) / len(union_)         if union_        else 0.0
                print(f'  K={k:<5} {precision:>5.2%} {recall:>5.2%} {jaccard:>5.2%}', end='')
                fold_record[f'k{k}_precision'] = precision
                fold_record[f'k{k}_recall']    = recall
                fold_record[f'k{k}_jaccard']   = jaccard
            print()
            records.append(fold_record)

        # Mean across folds for this feat_set
        set_records = [r for r in records if r['set'] == feat_set_label]
        print(f'  Mean  ', end='')
        for k in top_k_global_list:
            p_mean = np.mean([r[f'k{k}_precision'] for r in set_records])
            r_mean = np.mean([r[f'k{k}_recall']    for r in set_records])
            j_mean = np.mean([r[f'k{k}_jaccard']   for r in set_records])
            print(f'  K={k:<5} {p_mean:>5.2%} {r_mean:>5.2%} {j_mean:>5.2%}', end='')
        print()

    return pd.DataFrame(records)


