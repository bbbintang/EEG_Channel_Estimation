def create_feature_matrix(df, channels, config_name):
    print(f'\nCreating feature matrix for {config_name}...')
    files    = df[['file_id','subject','trial','stress_binary','stress_label']].drop_duplicates().reset_index(drop=True)
    features = sorted(df['feature_name'].unique())   # sorted → deterministic order
    print(f'  Samples        : {len(files)}')
    print(f'  Feature types  : {len(features)}')
    print(f'  Channels       : {len(channels)}')

    feature_data = {}
    for feat in features:
        feat_df = df[df['feature_name'] == feat].set_index('file_id')
        for ch in channels:
            if ch in feat_df.columns:
                feature_data[f'{feat}_{ch}'] = feat_df[ch]

    feat_matrix = pd.DataFrame(feature_data)
    result      = files.merge(feat_matrix, left_on='file_id', right_index=True, how='left')
    feat_cols   = [c for c in result.columns if c not in ['file_id','subject','trial','stress_binary','stress_label']]

    miss = result[feat_cols].isnull().sum().sum()
    if miss > 0:
        print(f'  Warning: {miss} missing values — filling with column mean')
        result[feat_cols] = result[feat_cols].fillna(result[feat_cols].mean())

    print(f'  Result shape   : {result.shape}  ({len(feat_cols)} feature×channel columns)')
    return result, feat_cols, features, list(channels)

