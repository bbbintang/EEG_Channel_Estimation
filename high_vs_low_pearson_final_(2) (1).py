def load_global_feature_ranking(config):
    """
    Load global feature correlation CSV.
    Handles both Pearson (correlations.csv) and Spearman (spearman_feature_binary.csv) formats.

    Pearson CSV columns : feature, correlation, abs_correlation, p_value, n_samples
    Spearman CSV columns: feature, spearman_rho, abs_rho, p_value, n_samples

    Returns sorted list of (feature_type, abs_corr), descending.
    """
    df = pd.read_csv(GLOBAL_FEATURE_CSVS[config])
    df.columns = [c.strip().lower().replace('-','_').replace(' ','_') for c in df.columns]

    # Detect feature column
    feat_col = next((c for c in df.columns if c in ('feature','feature_name')), None)
    if feat_col is None:
        feat_col = next(c for c in df.columns if 'feature' in c)

    # Detect absolute correlation column — prefer explicit 'abs_correlation' (Pearson) or 'abs_rho' (Spearman)
    if 'abs_correlation' in df.columns:
        abs_col = 'abs_correlation'
    elif 'abs_rho' in df.columns:
        abs_col = 'abs_rho'
    else:
        abs_col = next(c for c in df.columns if 'abs' in c)

    df = df.sort_values(abs_col, ascending=False).reset_index(drop=True)
    return list(zip(df[feat_col], df[abs_col]))


def compare_feature_rankings(global_ranked, per_fold_ranked, top_n_list=(3, 5, 10)):
    """
    Spearman rank correlation + Jaccard top-N between global and per-fold training rankings.
    """
    global_names = [n for n, _ in global_ranked]
    global_rank  = {n: i for i, n in enumerate(global_names)}
    records = []
    rho_list = []

    print(f'  {"Fold":<6} {"Spearman ρ":>12} {"p-value":>10}', end='')
    for n in top_n_list:
        print(f'  {"Top-"+str(n)+" Jaccard":>14}', end='')
    print()
    print(f'  {"-"*6} {"-"*12} {"-"*10}', end='')
    for _ in top_n_list:
        print(f'  {"-"*14}', end='')
    print()

    for fold_i, fold_ranking in enumerate(per_fold_ranked, 1):
        train_names = [r[0] for r in fold_ranking]
        train_rank  = {n: i for i, n in enumerate(train_names)}
        common = [n for n in global_names if n in train_rank]
        if len(common) < 3:
            print(f'  Fold {fold_i}: too few common features ({len(common)}), skipping')
            continue

        rho, p = spearmanr([global_rank[n] for n in common],
                           [train_rank[n]  for n in common])
        rho_list.append(rho)

        print(f'  {fold_i:<6} {rho:>12.4f} {p:>10.4f}', end='')
        for n in top_n_list:
            g_top = set(global_names[:n])
            t_top = set(train_names[:n])
            jac   = len(g_top & t_top) / len(g_top | t_top) if (g_top | t_top) else 0.0
            print(f'  {jac:>14.2%}', end='')
        print()
        records.append({'fold': fold_i, 'rho': rho, 'p': p, 'train_names': train_names})

    if rho_list:
        mean_rho = np.mean(rho_list)
        print(f'\n  Mean Spearman ρ: {mean_rho:.4f} ± {np.std(rho_list):.4f}')
        if   mean_rho >= 0.8: interp = 'VERY HIGH — training subset reproduces global ranking reliably'
        elif mean_rho >= 0.6: interp = 'HIGH — minor variation, training subset sufficient'
        elif mean_rho >= 0.4: interp = 'MODERATE — some ranking shifts; caution advised'
        else:                  interp = 'LOW — training subset unreliable; full data preferred'
        print(f'  Interpretation : {interp}')

    return records


