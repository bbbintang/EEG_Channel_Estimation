def run_statistical_tests(results_df, channel_config):
    subset = results_df[results_df['channel_config'] == channel_config]
    models = list(subset['model'].unique())

    print(f'\n{"="*80}')
    print(f'STATISTICAL TESTS — {channel_config}')
    print(f'{"="*80}')
    print('Paired observations: fold-level accuracy (n=3 folds per model)')
    print('H0: No accuracy difference between HIGH and LOW feature sets')
    print()
    print(f'  {"Model":<10} {"HIGH":>8} {"LOW":>8} {"Diff":>8}'
          f' {"Wilcoxon p":>12} {"t-test p":>10} {"Sig":>6}')
    print(f'  {"-"*10} {"-"*8} {"-"*8} {"-"*8} {"-"*12} {"-"*10} {"-"*6}')

    records = []
    for model in models:
        md_      = subset[subset['model'] == model].sort_values('fold')
        h_acc    = md_[md_['feature_set'] == 'HIGH']['accuracy'].values
        l_acc    = md_[md_['feature_set'] == 'LOW']['accuracy'].values
        diff     = h_acc.mean() - l_acc.mean()

        try:
            w_p = 1.0 if np.all(h_acc == l_acc) else wilcoxon(h_acc, l_acc)[1]
        except Exception:
            w_p = float('nan')
        try:
            t_p = ttest_rel(h_acc, l_acc)[1]
        except Exception:
            t_p = float('nan')

        sig = 'YES *' if (not np.isnan(w_p) and w_p < 0.05) else 'no'
        print(f'  {model:<10} {h_acc.mean():>8.4f} {l_acc.mean():>8.4f} {diff:>+8.4f}'
              f' {w_p:>12.4f} {t_p:>10.4f} {sig:>6}')
        records.append({'model': model, 'high_acc': h_acc.mean(), 'low_acc': l_acc.mean(),
                        'diff': diff, 'wilcoxon_p': w_p, 'ttest_p': t_p,
                        'significant': bool(not np.isnan(w_p) and w_p < 0.05)})

    n_sig = sum(r['significant'] for r in records)
    print(f'\n  Significant (p<0.05): {n_sig}/{len(models)} models')
    if n_sig == 0:
        print('  → H0 not rejected for any model.')
        print('    Note: with only 3 folds, statistical power is inherently limited.')
    else:
        print(f'  → H0 rejected for: {[r["model"] for r in records if r["significant"]]}')

    return pd.DataFrame(records)

