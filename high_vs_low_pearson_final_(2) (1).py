"""## 6. Main Experiment Loop

Per fold:
1. Scale training data (fit on train only, no leakage)
2. Rank feature types by avg |Spearman ρ| across all channels (on training data only)
3. HIGH = top-N feat types × ALL channels; LOW = bottom-N × ALL channels
4. Feature sets evaluated: HIGH, LOW, HIGH+LOW
5. Train 4 classifiers → accuracy, precision, recall, F1, confusion matrix

"""

def run_experiment(data, folds, feature_cols, feat_types, channels, channel_config='32ch'):
    results          = []
    feature_rankings = []
    confusion_mats   = {}
    models           = get_models()

    for fold_info in folds:
        fold_num  = fold_info['fold']
        train_idx = fold_info['train_idx']
        test_idx  = fold_info['test_idx']

        print(f'\n  Fold {fold_num} (test=trial{fold_info["test_trial"]})', end='')

        X_train_full   = data.loc[train_idx, feature_cols]
        y_train        = data.loc[train_idx, 'stress_binary']   # for model training & evaluation
        y_train_cont   = data.loc[train_idx, 'stress_label']    # for Pearson ranking (continuous 1–10)
        X_test_full    = data.loc[test_idx,  feature_cols]
        y_test         = data.loc[test_idx,  'stress_binary']

        # ── Scale (fit on train only) ──────────────────────────────────────
        scaler     = StandardScaler()
        X_train_sc = pd.DataFrame(scaler.fit_transform(X_train_full),
                                   columns=feature_cols, index=train_idx)
        X_test_sc  = pd.DataFrame(scaler.transform(X_test_full),
                                   columns=feature_cols, index=test_idx)

        # ── Pearson ranking on training data (continuous label 1–10) ───────
        ranked, col_rho = rank_feature_types_by_pearson(
            X_train_sc, y_train_cont, feat_types, channels)

        high_cols, low_cols, high_feats, low_feats = select_feature_sets(
            ranked, channels, N_TOP_FEATURES, N_BOTTOM_FEATURES)

        feature_rankings.append({
            'fold'      : fold_num,
            'ranked'    : ranked,
            'col_rho'   : col_rho,
            'high_feats': high_feats,
            'low_feats' : low_feats,
            'high_cols' : high_cols,
            'low_cols'  : low_cols,
        })

        print(f'  |  HIGH: {high_feats}')
        print(f'           LOW:  {low_feats}')

        # ── Feature sets ───────────────────────────────────────────────────
        combined_cols = list(dict.fromkeys(high_cols + low_cols))
        feature_sets  = {
            'HIGH'    : high_cols,
            'LOW'     : low_cols,
            'HIGH+LOW': combined_cols
        }

        for feat_set_name, selected in feature_sets.items():
            selected = [c for c in selected if c in X_train_sc.columns]
            X_tr     = X_train_sc[selected]
            X_te     = X_test_sc[selected]

            for model_name, model in models.items():
                model.fit(X_tr, y_train)
                y_pred = model.predict(X_te)
                cm     = confusion_matrix(y_test, y_pred)
                confusion_mats[(fold_num, feat_set_name, model_name)] = cm

                results.append({
                    'channel_config': channel_config,
                    'n_channels'    : len(channels),
                    'fold'          : fold_num,
                    'test_trial'    : fold_info['test_trial'],
                    'feature_set'   : feat_set_name,
                    'n_feat_types'  : (N_TOP_FEATURES if feat_set_name == 'HIGH'
                                       else N_BOTTOM_FEATURES if feat_set_name == 'LOW'
                                       else N_TOP_FEATURES + N_BOTTOM_FEATURES),
                    'n_columns'     : len(selected),
                    'model'         : model_name,
                    'accuracy'      : accuracy_score(y_test, y_pred),
                    'precision'     : precision_score(y_test, y_pred, zero_division=0),
                    'recall'        : recall_score(y_test, y_pred, zero_division=0),
                    'f1'            : f1_score(y_test, y_pred, zero_division=0),
                    'tn': cm[0,0], 'fp': cm[0,1], 'fn': cm[1,0], 'tp': cm[1,1]
                })

    return pd.DataFrame(results), feature_rankings, confusion_mats

