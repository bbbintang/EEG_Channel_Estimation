def extract_feature_per_channel(data: np.ndarray, feature_name: str, fs: int = 128) -> np.ndarray:
    """
    Extract one feature for each channel.

    Args:
        data: EEG data (samples, n_channels_work) - ALREADY FILTERED
        feature_name: Name of feature (e.g., 'time_RMS', 'freq_ALPHA_power')
        fs: Sampling frequency

    Returns:
        Array of values per channel (n_channels_work,)
    """
    n_ch = data.shape[1]
    values = np.zeros(n_ch)

    # TIME DOMAIN
    if feature_name.startswith('time_'):
        feat_type = feature_name.replace('time_', '')

        for ch in range(n_ch):
            ch_data = data[:, ch]

            if feat_type == 'MAV':
                values[ch] = np.mean(np.abs(ch_data))
            elif feat_type == 'RMS':
                values[ch] = np.sqrt(np.mean(ch_data ** 2))
            elif feat_type == 'STD':
                values[ch] = np.std(ch_data)
            elif feat_type == 'VAR':
                values[ch] = np.var(ch_data)
            elif feat_type == 'ZCR':
                values[ch] = np.sum(np.diff(np.sign(ch_data)) != 0)
            elif feat_type == 'KURT':
                from scipy.stats import kurtosis
                values[ch] = kurtosis(ch_data)
            elif feat_type == 'SKEW':
                from scipy.stats import skew
                values[ch] = skew(ch_data)
            elif feat_type == 'MEDIAN':
                values[ch] = np.median(ch_data)
            elif feat_type == 'PTP':
                values[ch] = np.ptp(ch_data)
            elif feat_type == 'ENERGY':
                values[ch] = np.sum(ch_data ** 2)
            elif feat_type == 'MIN':
                values[ch] = np.min(ch_data)
            elif feat_type == 'MAX':
                values[ch] = np.max(ch_data)
            elif feat_type == 'SAD':
                values[ch] = np.sum(np.abs(np.diff(ch_data)))

    # FREQUENCY DOMAIN
    elif feature_name.startswith('freq_'):
        for ch in range(n_ch):
            ch_data = data[:, ch]
            f, psd = welch(ch_data, fs=fs, nperseg=min(256, len(ch_data)))

            # Band selection
            if 'DELTA' in feature_name:
                idx = np.logical_and(f >= 1, f <= 4)
            elif 'THETA' in feature_name:
                idx = np.logical_and(f >= 4, f <= 8)
            elif 'ALPHA' in feature_name:
                idx = np.logical_and(f >= 8, f <= 13)
            elif 'BETA' in feature_name:
                idx = np.logical_and(f >= 13, f <= 30)
            elif 'GAMMA' in feature_name:
                idx = np.logical_and(f >= 30, f <= 50)
            elif 'TOTAL' in feature_name:
                idx = f >= 1

            # Compute metric
            if '_rel' in feature_name:
                total_power = np.trapz(psd[f >= 1], f[f >= 1])
                band_power = np.trapz(psd[idx], f[idx])
                values[ch] = band_power / total_power if total_power > 0 else 0
            elif '_power' in feature_name:
                values[ch] = np.trapz(psd[idx], f[idx])
            elif 'peak_freq' in feature_name:
                values[ch] = f[np.argmax(psd)]
            elif 'mean_freq' in feature_name:
                values[ch] = np.sum(f * psd) / np.sum(psd)
            elif 'median_freq' in feature_name:
                cum = np.cumsum(psd)
                values[ch] = f[np.where(cum >= cum[-1]/2)[0][0]]
            elif 'spectral_spread' in feature_name:
                mf = np.sum(f * psd) / np.sum(psd)
                values[ch] = np.sqrt(np.sum(((f - mf)**2) * psd) / np.sum(psd))
            elif 'theta_alpha_ratio' in feature_name:
                theta_idx = np.logical_and(f >= 4, f <= 8)
                alpha_idx = np.logical_and(f >= 8, f <= 13)
                theta_p = np.trapz(psd[theta_idx], f[theta_idx])
                alpha_p = np.trapz(psd[alpha_idx], f[alpha_idx])
                values[ch] = theta_p / alpha_p if alpha_p > 0 else 0

    # TIME-FREQUENCY
    elif feature_name.startswith('tf_'):
        for ch in range(n_ch):
            _, _, Zxx = signal.stft(data[:, ch], fs=fs, nperseg=256, noverlap=128)
            S = np.abs(Zxx) ** 2

            if 'stft_energy' in feature_name:
                values[ch] = np.sum(S)
            elif 'entropy' in feature_name:
                S_norm = S / (np.sum(S) + 1e-12)
                values[ch] = -np.sum(S_norm * np.log(S_norm + 1e-12))

    # WAVELET
    elif feature_name.startswith('wavelet_'):
        for ch in range(n_ch):
            coeffs = pywt.wavedec(data[:, ch], 'db4', level=4)

            if 'energy_L' in feature_name:
                level = int(feature_name.split('_L')[-1])
                values[ch] = np.sum(coeffs[level] ** 2)
            elif 'total_energy' in feature_name:
                values[ch] = sum(np.sum(c**2) for c in coeffs)
            elif 'mean_entropy' in feature_name:
                ents = []
                for c in coeffs:
                    if len(c) > 0:
                        p = np.abs(c) / (np.sum(np.abs(c)) + 1e-10)
                        ents.append(entropy(p + 1e-10))
                values[ch] = np.mean(ents)

    # NONLINEAR
    elif feature_name.startswith('nonlinear_'):
        ft = feature_name[len('nonlinear_'):]
        for ch in range(n_ch):
            x = data[:, ch].astype(float)
            # if   ft == 'ApEn'              : values[ch] = _apen(x)
            # elif ft == 'PermEn'            : values[ch] = _perm_entropy(x)
            if ft == 'HiguchiFD'        : values[ch] = _higuchi_fd(x)
            elif ft == 'KatzFD'           : values[ch] = _katz_fd(x)
            elif ft == 'PetrosianFD'      : values[ch] = _petrosian_fd(x)
            elif ft == 'HjorthActivity'   : values[ch] = float(np.var(x))
            elif ft == 'HjorthMobility'   :
                act = np.var(x)
                d1  = np.diff(x)
                values[ch] = float(np.sqrt(np.var(d1) / act)) if act > 0 else 0.0
            elif ft == 'HjorthComplexity' :
                act = np.var(x); d1 = np.diff(x); d2 = np.diff(d1)
                mob = float(np.sqrt(np.var(d1) / act)) if act > 0 else 0.0
                mob2 = float(np.sqrt(np.var(d2) / np.var(d1))) if np.var(d1) > 0 else 0.0
                values[ch] = float(mob2 / mob) if mob > 0 else 0.0


    # CONNECTIVITY (compute average connectivity per channel)
    elif feature_name.startswith('conn_'):
        conn_matrix = np.zeros((n_ch, n_ch))

        if 'diff_entropy' in feature_name:
            # Per-channel metric
            for ch in range(n_ch):
                var = np.var(data[:, ch])
                values[ch] = 0.5 * np.log(2 * np.pi * np.e * var) if var > 0 else 0

        else:  # PLV, PLI, wPLI
            phases = np.angle(hilbert(data, axis=0))

            for i in range(n_ch):
                for j in range(i+1, n_ch):
                    phase_diff = phases[:, i] - phases[:, j]

                    if 'plv' in feature_name:
                        val = np.abs(np.mean(np.exp(1j * phase_diff)))
                    elif 'pli' in feature_name and 'wpli' not in feature_name:
                        val = np.abs(np.mean(np.sign(np.sin(phase_diff))))
                    elif 'wpli' in feature_name:
                        imag = np.imag(np.exp(1j * phase_diff))
                        denom = np.mean(np.abs(imag))
                        val = np.abs(np.mean(imag)) / denom if denom > 0 else 0
                    else:
                        val = 0

                    conn_matrix[i, j] = val
                    conn_matrix[j, i] = val

            # Average per channel
            for ch in range(n_ch):
                other_chs = np.delete(conn_matrix[ch, :], ch)
                values[ch] = np.mean(other_chs)

    return values

print("✓ Per-channel extraction function defined")

