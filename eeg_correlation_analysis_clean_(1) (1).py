def parse_filename(filepath: str) -> Dict[str, any]:
    """Parse filename to extract metadata."""
    filename = os.path.basename(filepath)
    match = re.match(r'(\w+)_sub_(\d+)_trial(\d+)\.mat', filename)
    if match:
        return {
            'file_id': filename.replace('.mat', ''),
            'task': match.group(1),
            'subject': int(match.group(2)),
            'trial': int(match.group(3))
        }
    return None

MAT_KEY = 'Clean_data'  # key inside the .mat file that holds the EEG array

def load_eeg_file(filepath: str) -> np.ndarray:
    """
    Load EEG data from a .mat file.

    The .mat file stores data as (n_channels, n_samples) under the key
    MAT_KEY ('Clean_data'). We transpose it to (n_samples, n_channels)
    to match the format expected by all downstream feature functions.

    Returns:
        np.ndarray of shape (n_samples, n_channels), dtype float64
    """
    mat = sio.loadmat(filepath)

    if MAT_KEY not in mat:
        available = [k for k in mat.keys() if not k.startswith('_')]
        raise KeyError(
            f"Key '{MAT_KEY}' not found in {filepath}. "
            f"Available keys: {available}. "
            f"Update MAT_KEY at the top of this section if needed."
        )

    data = mat[MAT_KEY].astype(np.float64)   # shape: (n_channels, n_samples)
    return data.T                              # transpose -> (n_samples, n_channels)

