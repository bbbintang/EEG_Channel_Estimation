def extract_time_features(data: np.ndarray) -> Dict[str, float]:
    """Extract 13 time-domain features."""
    # Flatten across channels (average)
    flat = data.flatten()

    from scipy.stats import kurtosis, skew

    return {
        'time_MAV': np.mean(np.abs(flat)),
        'time_RMS': np.sqrt(np.mean(flat ** 2)),
        'time_STD': np.std(flat),
        'time_VAR': np.var(flat),
        'time_ZCR': float(np.sum(np.diff(np.sign(flat)) != 0)),
        'time_KURT': kurtosis(flat),
        'time_SKEW': skew(flat),
        'time_MEDIAN': np.median(flat),
        'time_PTP': np.ptp(flat),
        'time_ENERGY': np.sum(flat ** 2),
        'time_MIN': np.min(flat),
        'time_MAX': np.max(flat),
        'time_SAD': np.sum(np.abs(np.diff(flat)))
    }

def extract_frequency_features(data: np.ndarray, fs: int = 128) -> Dict[str, float]:
    """Extract 18 frequency-domain features."""
    # Average PSD across channels
    psds = []
    for ch in range(data.shape[1]):
        f, psd = welch(data[:, ch], fs=fs, nperseg=min(256, len(data[:, ch])))
        psds.append(psd)

    psd_avg = np.mean(psds, axis=0)

    # Band power
    def band_power(freqs, psd, fmin, fmax):
        idx = np.logical_and(freqs >= fmin, freqs <= fmax)
        return np.trapz(psd[idx], freqs[idx])

    delta = band_power(f, psd_avg, 1, 4)
    theta = band_power(f, psd_avg, 4, 8)
    alpha = band_power(f, psd_avg, 8, 13)
    beta = band_power(f, psd_avg, 13, 30)
    gamma = band_power(f, psd_avg, 30, 50)
    total = band_power(f, psd_avg, 1, 50)

    # Spectral descriptors
    mean_freq = np.sum(f * psd_avg) / np.sum(psd_avg)
    cum_psd = np.cumsum(psd_avg)
    median_freq = f[np.where(cum_psd >= cum_psd[-1] / 2)[0][0]]
    spread = np.sqrt(np.sum(((f - mean_freq) ** 2) * psd_avg) / np.sum(psd_avg))

    return {
        'freq_DELTA_power': delta,
        'freq_THETA_power': theta,
        'freq_ALPHA_power': alpha,
        'freq_BETA_power': beta,
        'freq_GAMMA_power': gamma,
        'freq_DELTA_rel': delta / total if total > 0 else 0,
        'freq_THETA_rel': theta / total if total > 0 else 0,
        'freq_ALPHA_rel': alpha / total if total > 0 else 0,
        'freq_BETA_rel': beta / total if total > 0 else 0,
        'freq_GAMMA_rel': gamma / total if total > 0 else 0,
        'freq_TOTAL_power': total,
        'freq_peak_freq': f[np.argmax(psd_avg)],
        'freq_mean_freq': mean_freq,
        'freq_median_freq': median_freq,
        'freq_spectral_spread': spread,
        'freq_spectral_skewness': np.sum(((f - mean_freq) ** 3) * psd_avg) / (spread ** 3 * np.sum(psd_avg)),
        'freq_spectral_kurtosis': np.sum(((f - mean_freq) ** 4) * psd_avg) / (spread ** 4 * np.sum(psd_avg)),
        'freq_theta_alpha_ratio': theta / alpha if alpha > 0 else 0
    }

def extract_time_frequency_features(data: np.ndarray, fs: int = 128) -> Dict[str, float]:
    """Extract 2 time-frequency features."""
    # Average across channels
    energies = []
    entropies = []

    for ch in range(data.shape[1]):
        _, _, Zxx = signal.stft(data[:, ch], fs=fs, nperseg=256, noverlap=128)
        S = np.abs(Zxx) ** 2
        energies.append(np.sum(S))

        S_norm = S / (np.sum(S) + 1e-12)
        entropies.append(-np.sum(S_norm * np.log(S_norm + 1e-12)))

    return {
        'tf_stft_energy': np.mean(energies),
        'tf_entropy': np.mean(entropies)
    }

def extract_wavelet_features(data: np.ndarray) -> Dict[str, float]:
    """Extract 7 wavelet features."""
    # Average across channels
    all_energies = [[] for _ in range(5)]  # L0-L4
    all_entropies = []

    for ch in range(data.shape[1]):
        coeffs = pywt.wavedec(data[:, ch], 'db4', level=4)
        for i, c in enumerate(coeffs):
            all_energies[i].append(np.sum(c ** 2))

        # Entropy
        ents = []
        for c in coeffs:
            if len(c) > 0:
                prob = np.abs(c) / (np.sum(np.abs(c)) + 1e-10)
                ents.append(entropy(prob + 1e-10))
        all_entropies.append(np.mean(ents))

    return {
        'wavelet_energy_L0': np.mean(all_energies[0]),
        'wavelet_energy_L1': np.mean(all_energies[1]),
        'wavelet_energy_L2': np.mean(all_energies[2]),
        'wavelet_energy_L3': np.mean(all_energies[3]),
        'wavelet_energy_L4': np.mean(all_energies[4]),
        'wavelet_total_energy': np.mean([np.sum(e) for e in all_energies]),
        'wavelet_mean_entropy': np.mean(all_entropies)
    }

def extract_connectivity_features(data: np.ndarray, fs: int = 128) -> Dict[str, float]:
    """Extract 8 connectivity features."""
    n_ch = data.shape[1]

    # Differential entropy (per-channel, then average)
    diff_ents = []
    for ch in range(n_ch):
        var = np.var(data[:, ch])
        if var > 0:
            diff_ents.append(0.5 * np.log(2 * np.pi * np.e * var))

    # Phase-based connectivity
    phases = np.angle(hilbert(data, axis=0))
    plv_vals = []
    pli_vals = []
    wpli_vals = []

    for i in range(n_ch):
        for j in range(i+1, n_ch):
            phase_diff = phases[:, i] - phases[:, j]

            # PLV
            plv_vals.append(np.abs(np.mean(np.exp(1j * phase_diff))))

            # PLI
            pli_vals.append(np.abs(np.mean(np.sign(np.sin(phase_diff)))))

            # wPLI
            imag = np.imag(np.exp(1j * phase_diff))
            denom = np.mean(np.abs(imag))
            wpli_vals.append(np.abs(np.mean(imag)) / denom if denom > 0 else 0)

    return {
        'conn_diff_entropy': np.mean(diff_ents),
        'conn_plv': np.mean(plv_vals),
        'conn_pli': np.mean(pli_vals),
        'conn_wpli': np.mean(wpli_vals)
    }

