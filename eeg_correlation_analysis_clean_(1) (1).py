# ── Higuchi Fractal Dimension ────────────────────────────────
def _higuchi_fd(x: np.ndarray, kmax: int = 8) -> float:
    """Higuchi Fractal Dimension."""
    N = len(x)
    L = []
    for k in range(1, kmax + 1):
        Lk = []
        for m in range(1, k + 1):
            # Number of intervals
            idx = np.arange(m - 1, N, k)
            n_m = len(idx) - 1
            if n_m < 1:
                continue
            Lmk = np.sum(np.abs(np.diff(x[idx]))) * (N - 1) / (n_m * k)
            Lk.append(Lmk)
        if Lk:
            L.append((k, np.mean(Lk)))
    if len(L) < 2:
        return 0.0
    log_k = np.log(np.array([v[0] for v in L]))
    log_L = np.log(np.array([v[1] for v in L]) + 1e-12)
    return float(-np.polyfit(log_k, log_L, 1)[0])

# ── Katz Fractal Dimension ───────────────────────────────────
def _katz_fd(x: np.ndarray) -> float:
    """Katz Fractal Dimension."""
    diffs = np.abs(np.diff(x))
    L = np.sum(diffs)                      # Total length of the curve
    d = np.max(np.abs(x - x[0]))          # Max distance from first point
    n = len(x) - 1
    if d == 0 or n == 0 or L == 0:
        return 0.0
    return float(np.log10(n) / (np.log10(n) + np.log10(d / L)))

# ── Petrosian Fractal Dimension ──────────────────────────────
def _petrosian_fd(x: np.ndarray) -> float:
    """Petrosian Fractal Dimension."""
    N = len(x)
    d = np.diff(x)
    Ndelta = np.sum(d[1:] * d[:-1] < 0)   # Number of sign changes in derivative
    return float(np.log10(N) / (np.log10(N) + np.log10(N / (N + 0.4 * Ndelta))))

# ── Hjorth Parameters ────────────────────────────────────────
def _hjorth(x: np.ndarray) -> Tuple[float, float, float]:
    """Hjorth Activity, Mobility, Complexity."""
    activity = float(np.var(x))
    d1 = np.diff(x)
    mobility = float(np.sqrt(np.var(d1) / activity)) if activity > 0 else 0.0
    d2 = np.diff(d1)
    mob2 = float(np.sqrt(np.var(d2) / np.var(d1))) if np.var(d1) > 0 else 0.0
    complexity = float(mob2 / mobility) if mobility > 0 else 0.0
    return activity, mobility, complexity


