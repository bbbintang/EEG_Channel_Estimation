def get_stress_label(task: str, subject: int, trial: int, scales_df: pd.DataFrame) -> int:
    """
    Get stress label for specific trial.

    Scales.xlsx format: t{trial}_{task}
    Example: t1_math, t2_stroop, t3_mirror

    Args:
        task: Task name (e.g., 'Arithmetic', 'Stroop', 'Mirror_image')
        subject: Subject number (1-40)
        trial: Trial number (1-3)
        scales_df: DataFrame with stress labels

    Returns:
        Stress label (1-10) or np.nan if not found
    """
    # Map task name to column suffix
    task_suffix = TASK_MAP.get(task)
    if task_suffix is None:
        return np.nan

    # Build column name: t{trial}_{task}
    # Example: t1_math, t2_stroop, t3_mirror
    col_name = f"t{trial}_{task_suffix}"

    # Check if column exists
    if col_name not in scales_df.columns:
        return np.nan

    # Check if subject index is valid
    if subject < 1 or subject > len(scales_df):
        return np.nan

    # Get label (subject indexing: subject 1 = row 0)
    try:
        label = scales_df.loc[subject - 1, col_name]

        # Convert to int if valid
        if pd.isna(label):
            return np.nan

        return int(label)

    except Exception as e:
        return np.nan

